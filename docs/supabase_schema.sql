create table if not exists lecturas_robot (
  id bigint generated by default as identity primary key,
  timestamp timestamptz default now() not null,
  x_cm float,
  y_cm float,
  theta_rad float,
  gas_valor integer,
  gas_alerta boolean default false,
  front_cm float,
  left_cm float,
  right_cm float,
  robot_id text default 'robot1'
);

create table if not exists comandos_robot (
  id bigint generated by default as identity primary key,
  robot_id text default 'robot1',
  comando text not null,
  procesado boolean default false,
  created_at timestamptz default now()
);

alter table lecturas_robot enable row level security;
alter table comandos_robot enable row level security;

drop policy if exists "lecturas select" on lecturas_robot;
drop policy if exists "lecturas insert" on lecturas_robot;
drop policy if exists "comandos select" on comandos_robot;
drop policy if exists "comandos insert" on comandos_robot;
drop policy if exists "comandos update" on comandos_robot;

create policy "lecturas select" on lecturas_robot for select using (true);
create policy "lecturas insert" on lecturas_robot for insert with check (true);
create policy "comandos select" on comandos_robot for select using (true);
create policy "comandos insert" on comandos_robot for insert with check (true);
create policy "comandos update" on comandos_robot for update using (true);

-- Realtime para la app (idempotente)
do $$
begin
  begin
    alter publication supabase_realtime add table public.lecturas_robot;
  exception when duplicate_object then null;
  end;
  begin
    alter publication supabase_realtime add table public.comandos_robot;
  exception when duplicate_object then null;
  end;
end $$;

-- Índices útiles
create index if not exists idx_lecturas_robot_timestamp
  on lecturas_robot (timestamp desc);
create index if not exists idx_comandos_robot_pendientes
  on comandos_robot (robot_id, procesado, id);
